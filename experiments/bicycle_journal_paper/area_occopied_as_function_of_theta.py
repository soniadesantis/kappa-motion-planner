"""
Reference-tangent analysis for the initial C or C_b C maneuver.

The reference tangent is the tangent from the fixed initial position
p_0 to the target intermediate circle selected according to tau_1.

Convention
----------
tau_1 = +1:
    select the tangency point lying to the RIGHT of the directed line
    from p_0 to the target-circle center o_1.

tau_1 = -1:
    select the tangency point lying to the LEFT of that directed line.

The fixed reference mismatch is

    delta_ref = wrap(theta_0 - theta_ref),

where theta_ref is the heading of the selected point-to-circle tangent.

For each initial orientation, the script also computes

    delta_segment = wrap(theta_0 - theta_S),

and

    eta = wrap(theta_S - theta_ref),

where theta_S is the orientation of the actual straight segment
generated by the planner.

Outputs
-------
1. reference_tangent_geometry.pdf
2. representative_maneuvers_signed_reference_mismatch.pdf
3. required_width_signed_reference_mismatch.pdf
4. occupied_extents_signed_reference_mismatch.pdf
5. segment_angles_signed_reference_mismatch.pdf
6. arc_amplitudes_signed_reference_mismatch.pdf
7. reference_tangent_analysis.csv
"""

