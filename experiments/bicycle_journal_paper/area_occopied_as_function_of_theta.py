def plot_reference_tangent_geometry(
    *,
    start_position: np.ndarray,
    circle_center: np.ndarray,
    circle_radius: float,
    reference_tangent: dict[str, Any],
    output_path: Path | None = None,
) -> tuple[plt.Figure, plt.Axes]:
    """Plot both correct tangents and highlight the selected one."""
    start_position = np.asarray(
        start_position,
        dtype=float,
    )

    circle_center = np.asarray(
        circle_center,
        dtype=float,
    )

    figure, ax = plt.subplots(
        figsize=(
            7.0,
            6.0,
        )
    )

    target_circle_patch = Circle(
        xy=(
            circle_center[0],
            circle_center[1],
        ),
        radius=circle_radius,
        facecolor="0.93",
        edgecolor="black",
        linewidth=1.3,
    )

    ax.add_patch(
        target_circle_patch
    )

    ax.plot(
        start_position[0],
        start_position[1],
        marker="o",
        color="black",
        markersize=6,
        label=r"$\mathbf{p}_{0}$",
    )

    ax.plot(
        circle_center[0],
        circle_center[1],
        marker="+",
        color="black",
        markersize=10,
        label=r"$\mathbf{o}_{1}$",
    )

    # Directed centerline p_0 -> o_1.
    ax.plot(
        [
            start_position[0],
            circle_center[0],
        ],
        [
            start_position[1],
            circle_center[1],
        ],
        linestyle=":",
        linewidth=1.1,
        label=(
            r"Directed centerline "
            r"$\mathbf{p}_{0}\mathbf{o}_{1}$"
        ),
    )

    selected_tangent_point = np.asarray(
        reference_tangent[
            "tangent_point"
        ],
        dtype=float,
    )

    for candidate in reference_tangent[
        "all_candidates"
    ]:
        tangent_point = np.asarray(
            candidate[
                "tangent_point"
            ],
            dtype=float,
        )

        is_selected = np.allclose(
            tangent_point,
            selected_tangent_point,
        )

        side = candidate[
            "side_relative_to_centerline"
        ]

        ax.plot(
            [
                start_position[0],
                tangent_point[0],
            ],
            [
                start_position[1],
                tangent_point[1],
            ],
            linestyle=(
                "-"
                if is_selected
                else "--"
            ),
            linewidth=(
                2.2
                if is_selected
                else 1.2
            ),
            alpha=(
                1.0
                if is_selected
                else 0.65
            ),
            label=(
                f"Selected tangent: {side} tangency point"
                if is_selected
                else f"Other tangent: {side} tangency point"
            ),
        )

        ax.plot(
            tangent_point[0],
            tangent_point[1],
            marker="o",
            markersize=5,
        )

        # Radius to tangency point.
        ax.plot(
            [
                circle_center[0],
                tangent_point[0],
            ],
            [
                circle_center[1],
                tangent_point[1],
            ],
            linestyle=":",
            linewidth=1.0,
        )

        tangent_vector = (
            tangent_point
            - start_position
        )

        radius_vector = (
            tangent_point
            - circle_center
        )

        orthogonality = float(
            tangent_vector
            @ radius_vector
        )

        ax.text(
            tangent_point[0],
            tangent_point[1],
            "\n"
            rf"$\mathbf{{t}}^\top"
            rf"\mathbf{{r}}={orthogonality:.1e}$",
            fontsize=8,
        )

    all_points = np.vstack(
        (
            start_position[None, :],
            circle_center[None, :],
            np.vstack(
                [
                    candidate[
                        "tangent_point"
                    ]
                    for candidate
                    in reference_tangent[
                        "all_candidates"
                    ]
                ]
            ),
        )
    )

    minimum_coordinates = np.min(
        all_points,
        axis=0,
    )

    maximum_coordinates = np.max(
        all_points,
        axis=0,
    )

    total_span = max(
        np.max(
            maximum_coordinates
            - minimum_coordinates
        ),
        2.0
        * circle_radius,
    )

    margin = (
        0.20
        * total_span
    )

    ax.set_xlim(
        minimum_coordinates[0]
        - circle_radius
        - margin,
        maximum_coordinates[0]
        + circle_radius
        + margin,
    )

    ax.set_ylim(
        minimum_coordinates[1]
        - circle_radius
        - margin,
        maximum_coordinates[1]
        + circle_radius
        + margin,
    )

    ax.set_aspect(
        "equal",
        adjustable="box",
    )

    ax.set_xlabel(
        r"$x$"
    )

    ax.set_ylabel(
        r"$y$"
    )

    ax.set_title(
        "Fixed point-to-circle reference tangent"
        "\n"
        rf"$\tau_{{1}}={reference_tangent['tau1']:+d}$, "
        rf"selected side: "
        rf"$\mathrm{{{reference_tangent['required_side']}}}$, "
        rf"$\theta_{{\mathrm{{ref}}}}="
        rf"{np.rad2deg(reference_tangent['heading']):.2f}^\circ$"
    )

    ax.grid(
        True,
        linestyle=":",
        linewidth=0.5,
        alpha=0.35,
    )

    ax.legend(
        frameon=False,
    )

    figure.tight_layout()

    if output_path is not None:
        output_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        figure.savefig(
            output_path,
            bbox_inches="tight",
        )

    return figure, ax


