def main() -> None:
    """Run the full reference-tangent analysis."""
    bicycle = Bicycle(
        model="Bicycle circular"
    )

    R = float(
        bicycle.max_radius
    )

    start_position = (
        0.0,
        0.0,
    )

    # Replace this with the IntermediateCircle constructor from your
    # existing working script if additional arguments are required.
    target_circle = IntermediateCircle(
        center=Point(
            0.0,
            5.0,
        ),
        radius=R,
        turn_direction=+1,
        corner_point=Point(
            0.5,
            0.5,
        ),
    )

    theta_step_degrees = 0.5

    # Set to zero for a point vehicle.
    footprint_radius = (
        0.5
        * bicycle.width
    )

    representative_signed_mismatches = [
        -180.0,
        -150.0,
        -120.0,
        -90.0,
        -60.0,
        -30.0,
        0.0,
        30.0,
        60.0,
        90.0,
        120.0,
        150.0,
    ]

    output_directory = (
        Path(__file__).resolve().parent
        / "saved_figures"
        / "reference_tangent_analysis_corrected"
    )

    output_directory.mkdir(
        parents=True,
        exist_ok=True,
    )

    (
        results,
        failures,
        reference_tangent,
    ) = run_reference_tangent_sweep(
        bicycle=bicycle,
        target_circle=target_circle,
        start_position=start_position,
        theta_step_degrees=theta_step_degrees,
        footprint_radius=footprint_radius,
    )

    if not results:
        raise RuntimeError(
            "The sweep produced no successful trajectories."
        )

    start_position_array = np.asarray(
        start_position,
        dtype=float,
    )

    circle_center = np.array(
        [
            target_circle.center.x,
            target_circle.center.y,
        ],
        dtype=float,
    )

    plot_reference_tangent_geometry(
        start_position=start_position_array,
        circle_center=circle_center,
        circle_radius=float(
            target_circle.radius
        ),
        reference_tangent=reference_tangent,
        output_path=(
            output_directory
            / "reference_tangent_geometry.pdf"
        ),
    )

    plot_representative_maneuvers(
        results=results,
        target_mismatches_degrees=(
            representative_signed_mismatches
        ),
        R=R,
        footprint_radius=footprint_radius,
        output_path=(
            output_directory
            / "representative_maneuvers_signed_reference_mismatch.pdf"
        ),
    )

    plot_required_width(
        results=results,
        R=R,
        footprint_radius=footprint_radius,
        output_path=(
            output_directory
            / "required_width_signed_reference_mismatch.pdf"
        ),
    )

    plot_occupied_extents(
        results=results,
        R=R,
        output_path=(
            output_directory
            / "occupied_extents_signed_reference_mismatch.pdf"
        ),
    )

    plot_segment_angles(
        results=results,
        output_path=(
            output_directory
            / "segment_angles_signed_reference_mismatch.pdf"
        ),
    )

    plot_arc_amplitudes(
        results=results,
        output_path=(
            output_directory
            / "arc_amplitudes_signed_reference_mismatch.pdf"
        ),
    )

    save_results_csv(
        results=results,
        output_path=(
            output_directory
            / "reference_tangent_analysis.csv"
        ),
    )

    print_summary(
        results=results,
        failures=failures,
        reference_tangent=reference_tangent,
        R=R,
        footprint_radius=footprint_radius,
    )

    plt.show()


if __name__ == "__main__":
    main()