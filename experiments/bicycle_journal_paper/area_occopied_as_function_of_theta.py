def compute_point_to_circle_tangent_points(
    *,
    external_point: np.ndarray,
    circle_center: np.ndarray,
    circle_radius: float,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Compute the two tangent points from an external point to a circle.

    Let

        p = external point,
        c = circle center,
        d = c - p.

    The returned tangent points satisfy

        ||p_t - c|| = R,

    and

        (p_t - p)^T (p_t - c) = 0.
    """
    external_point = np.asarray(
        external_point,
        dtype=float,
    )

    circle_center = np.asarray(
        circle_center,
        dtype=float,
    )

    radius = float(
        circle_radius
    )

    if radius <= 0.0:
        raise ValueError(
            "The circle radius must be positive."
        )

    displacement = (
        circle_center
        - external_point
    )

    distance_squared = float(
        displacement @ displacement
    )

    radius_squared = radius**2

    if distance_squared <= radius_squared:
        raise ValueError(
            "The external point must lie strictly outside the circle."
        )

    perpendicular_displacement = np.array(
        [
            -displacement[1],
            displacement[0],
        ],
        dtype=float,
    )

    projection_coefficient = (
        distance_squared
        - radius_squared
    ) / distance_squared

    perpendicular_coefficient = (
        radius
        * np.sqrt(
            distance_squared
            - radius_squared
        )
        / distance_squared
    )

    tangent_point_plus = (
        external_point
        + projection_coefficient
        * displacement
        + perpendicular_coefficient
        * perpendicular_displacement
    )

    tangent_point_minus = (
        external_point
        + projection_coefficient
        * displacement
        - perpendicular_coefficient
        * perpendicular_displacement
    )

    return (
        tangent_point_plus,
        tangent_point_minus,
    )


def verify_tangent_point(
    *,
    external_point: np.ndarray,
    circle_center: np.ndarray,
    circle_radius: float,
    tangent_point: np.ndarray,
    tolerance: float = 1e-9,
) -> dict[str, float]:
    """
    Verify that a computed point lies on the circle and defines a tangent.

    The tangent condition is

        (p_t - p_0)^T (p_t - o_1) = 0.
    """
    external_point = np.asarray(
        external_point,
        dtype=float,
    )

    circle_center = np.asarray(
        circle_center,
        dtype=float,
    )

    tangent_point = np.asarray(
        tangent_point,
        dtype=float,
    )

    radius_vector = (
        tangent_point
        - circle_center
    )

    tangent_vector = (
        tangent_point
        - external_point
    )

    radius_residual = abs(
        np.linalg.norm(
            radius_vector
        )
        - circle_radius
    )

    orthogonality_residual = abs(
        float(
            tangent_vector
            @ radius_vector
        )
    )

    orthogonality_scale = max(
        1.0,
        np.linalg.norm(
            tangent_vector
        )
        * circle_radius,
    )

    if radius_residual > tolerance:
        raise RuntimeError(
            "The computed tangent point is not on the circle. "
            f"Residual: {radius_residual:.3e}."
        )

    if (
        orthogonality_residual
        > tolerance
        * orthogonality_scale
    ):
        raise RuntimeError(
            "The computed line is not tangent to the circle. "
            "Orthogonality residual: "
            f"{orthogonality_residual:.3e}."
        )

    return {
        "radius_residual": float(
            radius_residual
        ),
        "orthogonality_residual": float(
            orthogonality_residual
        ),
    }


def classify_tangency_point_relative_to_centerline(
    *,
    start_position: np.ndarray,
    circle_center: np.ndarray,
    tangent_point: np.ndarray,
) -> Literal["left", "right", "collinear"]:
    """
    Classify a tangency point relative to the directed centerline

        start_position -> circle_center.

    In a standard x-right, y-up frame:

        cross(centerline, tangent_offset) > 0  -> left,
        cross(centerline, tangent_offset) < 0  -> right.
    """
    start_position = np.asarray(
        start_position,
        dtype=float,
    )

    circle_center = np.asarray(
        circle_center,
        dtype=float,
    )

    tangent_point = np.asarray(
        tangent_point,
        dtype=float,
    )

    centerline = (
        circle_center
        - start_position
    )

    tangent_offset = (
        tangent_point
        - start_position
    )

    side_value = cross_2d(
        centerline,
        tangent_offset,
    )

    tolerance = 1e-12

    if side_value > tolerance:
        return "left"

    if side_value < -tolerance:
        return "right"

    return "collinear"


def compute_reference_tangent_from_turn_direction(
    *,
    start_position: np.ndarray,
    circle_center: np.ndarray,
    circle_radius: float,
    tau1: int,
) -> dict[str, Any]:
    """
    Compute the reference tangent selected according to tau1.

    Convention
    ----------
    tau1 = +1:
        tangency point to the right of the directed centerline.

    tau1 = -1:
        tangency point to the left of the directed centerline.
    """
    if tau1 not in (-1, +1):
        raise ValueError(
            f"Expected tau1 in {{-1, +1}}, received {tau1}."
        )

    start_position = np.asarray(
        start_position,
        dtype=float,
    )

    circle_center = np.asarray(
        circle_center,
        dtype=float,
    )

    tangent_points = (
        compute_point_to_circle_tangent_points(
            external_point=start_position,
            circle_center=circle_center,
            circle_radius=circle_radius,
        )
    )

    required_side = (
        "right"
        if tau1 == +1
        else "left"
    )

    candidates: list[dict[str, Any]] = []

    for tangent_point in tangent_points:
        verification = verify_tangent_point(
            external_point=start_position,
            circle_center=circle_center,
            circle_radius=circle_radius,
            tangent_point=tangent_point,
        )

        side = (
            classify_tangency_point_relative_to_centerline(
                start_position=start_position,
                circle_center=circle_center,
                tangent_point=tangent_point,
            )
        )

        tangent_vector = (
            tangent_point
            - start_position
        )

        tangent_length = float(
            np.linalg.norm(
                tangent_vector
            )
        )

        tangent_direction = (
            tangent_vector
            / tangent_length
        )

        tangent_heading = float(
            np.arctan2(
                tangent_direction[1],
                tangent_direction[0],
            )
        )

        candidates.append(
            {
                "tangent_point": tangent_point,
                "heading": tangent_heading,
                "direction": tangent_direction,
                "length": tangent_length,
                "side_relative_to_centerline": side,
                **verification,
            }
        )

    matching_candidates = [
        candidate
        for candidate in candidates
        if candidate[
            "side_relative_to_centerline"
        ]
        == required_side
    ]

    if len(matching_candidates) != 1:
        raise RuntimeError(
            "Could not uniquely select the reference tangent. "
            f"tau1={tau1}, required side={required_side}, "
            f"candidates={candidates}."
        )

    selected_candidate = (
        matching_candidates[0]
    )

    selected_candidate[
        "all_candidates"
    ] = candidates

    selected_candidate[
        "tau1"
    ] = tau1

    selected_candidate[
        "required_side"
    ] = required_side

    return selected_candidate


