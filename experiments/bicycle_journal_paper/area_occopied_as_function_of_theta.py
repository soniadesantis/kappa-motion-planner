def branch_label(
    result: dict[str, Any],
) -> str:
    """Return a label including family and initial turn direction."""
    return (
        f"{result['family_plain']}, "
        rf"$\tau_{{0}}={result['tau0']:+d}$"
    )


def branch_marker(
    family_name: str,
    tau0: int,
) -> str:
    """Assign one marker per family/turn-direction branch."""
    marker_map = {
        ("C", +1): "o",
        ("C", -1): "^",
        ("CbC", +1): "s",
        ("CbC", -1): "D",
    }

    return marker_map[
        (
            family_name,
            tau0,
        )
    ]


def split_results_by_branch(
    results: list[dict[str, Any]],
) -> list[
    tuple[
        str,
        int,
        list[dict[str, Any]],
    ]
]:
    """Split successful results by family and tau0."""
    branches = []

    for family_name in (
        "C",
        "CbC",
    ):
        for tau0 in (
            -1,
            +1,
        ):
            branch_results = [
                result
                for result in results
                if (
                    result[
                        "family_plain"
                    ]
                    == family_name
                    and result[
                        "tau0"
                    ]
                    == tau0
                )
            ]

            if branch_results:
                branches.append(
                    (
                        family_name,
                        tau0,
                        branch_results,
                    )
                )

    return branches


def add_sampled_footprint_sweep(
    *,
    ax: plt.Axes,
    coordinates: np.ndarray,
    footprint_radius: float,
    stride: int = 1,
) -> None:
    """Plot a sampled approximation of the swept circular footprint."""
    if footprint_radius <= 0.0:
        return

    coordinates = np.asarray(
        coordinates,
        dtype=float,
    )

    for point in coordinates[::stride]:
        footprint_disk = Circle(
            xy=(
                point[0],
                point[1],
            ),
            radius=footprint_radius,
            facecolor="0.5",
            edgecolor="none",
            alpha=0.04,
            zorder=1,
        )

        ax.add_patch(
            footprint_disk
        )


def draw_heading_arrow(
    *,
    ax: plt.Axes,
    angle: float,
    length: float,
    label: str,
    linestyle: str = "-",
) -> None:
    """Draw an angle arrow from the local-frame origin."""
    endpoint = (
        length
        * unit_vector(
            angle
        )
    )

    ax.annotate(
        "",
        xy=(
            endpoint[0],
            endpoint[1],
        ),
        xytext=(
            0.0,
            0.0,
        ),
        arrowprops={
            "arrowstyle": "-|>",
            "linewidth": 1.2,
            "linestyle": linestyle,
            "color": "black",
            "shrinkA": 0,
            "shrinkB": 0,
        },
        zorder=20,
    )

    label_position = (
        1.18
        * endpoint
    )

    ax.text(
        label_position[0],
        label_position[1],
        label,
        horizontalalignment="center",
        verticalalignment="center",
        fontsize=8,
        zorder=21,
    )


