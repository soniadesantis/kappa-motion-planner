def wrap_to_pi(
    angle: float | np.ndarray,
) -> float | np.ndarray:
    """Wrap an angle to [-pi, pi)."""
    return np.arctan2(
        np.sin(angle),
        np.cos(angle),
    )


def signed_angle_difference(
    theta_a: float,
    theta_b: float,
) -> float:
    """Return wrap(theta_a - theta_b)."""
    return float(
        wrap_to_pi(
            theta_a - theta_b
        )
    )


def unit_vector(
    theta: float,
) -> np.ndarray:
    """Return the unit vector associated with angle theta."""
    return np.array(
        [
            np.cos(theta),
            np.sin(theta),
        ],
        dtype=float,
    )


def left_normal(
    vector: np.ndarray,
) -> np.ndarray:
    """Rotate a two-dimensional vector counterclockwise by pi/2."""
    vector = np.asarray(
        vector,
        dtype=float,
    )

    return np.array(
        [
            -vector[1],
            vector[0],
        ],
        dtype=float,
    )


def cross_2d(
    vector_a: np.ndarray,
    vector_b: np.ndarray,
) -> float:
    """Return the scalar two-dimensional cross product."""
    vector_a = np.asarray(
        vector_a,
        dtype=float,
    )

    vector_b = np.asarray(
        vector_b,
        dtype=float,
    )

    return float(
        vector_a[0] * vector_b[1]
        - vector_a[1] * vector_b[0]
    )


