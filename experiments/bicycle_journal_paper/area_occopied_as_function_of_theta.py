def extract_initial_circular_maneuver(
    trajectory: list[Any],
) -> dict[str, Any]:
    """
    Extract the initial circular maneuver and the first straight segment.

    Accepted structures before the first straight primitive:

        C S
        C_b C S
    """
    if not trajectory:
        raise ValueError(
            "The planner returned an empty trajectory."
        )

    circular_primitives: list[Any] = []

    tangent_segment = None
    forward_arc = None
    backward_arc = None

    for primitive in trajectory:
        if isinstance(
            primitive,
            LinearSegmentUnicycle,
        ):
            tangent_segment = primitive
            break

        if isinstance(
            primitive,
            BackwardArc,
        ):
            if backward_arc is not None:
                raise RuntimeError(
                    "More than one backward arc was found before "
                    "the first straight segment."
                )

            backward_arc = primitive

            circular_primitives.append(
                primitive
            )

            continue

        if isinstance(
            primitive,
            CurvilinearArcUnicycle,
        ):
            if forward_arc is not None:
                raise RuntimeError(
                    "More than one forward arc was found before "
                    "the first straight segment."
                )

            forward_arc = primitive

            circular_primitives.append(
                primitive
            )

            continue

        raise RuntimeError(
            "Unexpected primitive before the first straight segment: "
            f"{type(primitive).__name__}."
        )

    if forward_arc is None:
        raise RuntimeError(
            "No forward circular arc was found."
        )

    if tangent_segment is None:
        raise RuntimeError(
            "No outgoing straight segment was found."
        )

    has_backward_arc = (
        backward_arc is not None
    )

    return {
        "circular_primitives": circular_primitives,
        "tangent_segment": tangent_segment,
        "forward_arc": forward_arc,
        "backward_arc": backward_arc,
        "tau0": int(
            forward_arc.turn_direction
        ),
        "has_backward_arc": has_backward_arc,
        "family_plain": (
            "CbC"
            if has_backward_arc
            else "C"
        ),
        "family_latex": (
            r"$C_{\mathrm{b}}C$"
            if has_backward_arc
            else r"$C$"
        ),
    }


def concatenate_primitive_coordinates(
    primitives: list[Any],
) -> np.ndarray:
    """Concatenate the coordinates of consecutive primitives."""
    if not primitives:
        raise ValueError(
            "No primitives were provided."
        )

    coordinate_blocks: list[np.ndarray] = []

    for primitive_index, primitive in enumerate(
        primitives
    ):
        coordinates = np.asarray(
            primitive.path_coordinates,
            dtype=float,
        )

        if (
            coordinates.ndim != 2
            or coordinates.shape[1] != 2
        ):
            raise ValueError(
                "Expected path coordinates with shape (N, 2)."
            )

        if primitive_index > 0:
            coordinates = (
                coordinates[1:]
            )

        coordinate_blocks.append(
            coordinates
        )

    return np.vstack(
        coordinate_blocks
    )


# =====================================================================
# Fixed reference frame
# =====================================================================

def transform_to_reference_frame(
    *,
    world_coordinates: np.ndarray,
    frame_origin: np.ndarray,
    theta_reference: float,
) -> np.ndarray:
    """
    Express world points in the fixed reference-tangent frame.

    The local axes are:

        s_ref: along theta_ref,
        q_ref: positive to the left of theta_ref.
    """
    world_coordinates = np.asarray(
        world_coordinates,
        dtype=float,
    )

    frame_origin = np.asarray(
        frame_origin,
        dtype=float,
    )

    tangent_direction = unit_vector(
        theta_reference
    )

    normal_direction = left_normal(
        tangent_direction
    )

    relative_coordinates = (
        world_coordinates
        - frame_origin[None, :]
    )

    s_coordinates = (
        relative_coordinates
        @ tangent_direction
    )

    q_coordinates = (
        relative_coordinates
        @ normal_direction
    )

    return np.column_stack(
        (
            s_coordinates,
            q_coordinates,
        )
    )


# =====================================================================
# Spatial metrics
# =====================================================================

def compute_spatial_metrics(
    *,
    reference_coordinates: np.ndarray,
    footprint_radius: float,
) -> dict[str, float]:
    """
    Compute the occupied spatial extent in the reference-tangent frame.
    """
    coordinates = np.asarray(
        reference_coordinates,
        dtype=float,
    )

    s_coordinates = (
        coordinates[:, 0]
    )

    q_coordinates = (
        coordinates[:, 1]
    )

    s_min = float(
        np.min(
            s_coordinates
        )
    )

    s_max = float(
        np.max(
            s_coordinates
        )
    )

    q_min = float(
        np.min(
            q_coordinates
        )
    )

    q_max = float(
        np.max(
            q_coordinates
        )
    )

    lateral_path_width = (
        q_max
        - q_min
    )

    longitudinal_path_width = (
        s_max
        - s_min
    )

    return {
        "s_ref_min": s_min,
        "s_ref_max": s_max,
        "q_ref_min": q_min,
        "q_ref_max": q_max,
        "q_ref_abs_max": float(
            np.max(
                np.abs(
                    q_coordinates
                )
            )
        ),
        "lateral_path_width": float(
            lateral_path_width
        ),
        "longitudinal_path_width": float(
            longitudinal_path_width
        ),
        "required_strip_width": float(
            lateral_path_width
            + 2.0
            * footprint_radius
        ),
    }


