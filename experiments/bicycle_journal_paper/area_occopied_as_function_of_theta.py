def select_representative_signed_cases(
    *,
    results: list[dict[str, Any]],
    target_mismatches_degrees: list[float],
) -> list[dict[str, Any]]:
    """Select cases closest to requested signed reference mismatches."""
    selected_results = []

    for target_mismatch in target_mismatches_degrees:
        selected_result = min(
            results,
            key=lambda result: abs(
                result[
                    "delta_reference_degrees"
                ]
                - target_mismatch
            ),
        )

        selected_results.append(
            selected_result
        )

    return selected_results


def plot_representative_maneuvers(
    *,
    results: list[dict[str, Any]],
    target_mismatches_degrees: list[float],
    R: float,
    footprint_radius: float,
    output_path: Path | None = None,
) -> tuple[
    plt.Figure,
    np.ndarray,
    list[dict[str, Any]],
]:
    """Plot representative trajectories in the fixed reference frame."""
    selected_results = (
        select_representative_signed_cases(
            results=results,
            target_mismatches_degrees=target_mismatches_degrees,
        )
    )

    number_of_panels = len(
        selected_results
    )

    number_of_columns = min(
        4,
        number_of_panels,
    )

    number_of_rows = math.ceil(
        number_of_panels
        / number_of_columns
    )

    figure, axes = plt.subplots(
        number_of_rows,
        number_of_columns,
        figsize=(
            3.8
            * number_of_columns,
            3.6
            * number_of_rows,
        ),
        squeeze=False,
    )

    axes_flat = axes.ravel()

    for panel_index, (
        target_mismatch,
        result,
    ) in enumerate(
        zip(
            target_mismatches_degrees,
            selected_results,
        )
    ):
        ax = axes_flat[
            panel_index
        ]

        coordinates = np.asarray(
            result[
                "reference_coordinates"
            ],
            dtype=float,
        )

        add_sampled_footprint_sweep(
            ax=ax,
            coordinates=coordinates,
            footprint_radius=footprint_radius,
            stride=1,
        )

        ax.plot(
            coordinates[:, 0],
            coordinates[:, 1],
            linewidth=2.2,
            zorder=5,
        )

        ax.plot(
            0.0,
            0.0,
            marker="o",
            color="black",
            markersize=5,
            zorder=15,
        )

        # In the reference frame, theta_ref = 0.
        draw_heading_arrow(
            ax=ax,
            angle=0.0,
            length=0.50 * R,
            label=r"$\theta_{\mathrm{ref}}$",
            linestyle="-",
        )

        draw_heading_arrow(
            ax=ax,
            angle=result[
                "delta_reference"
            ],
            length=0.50 * R,
            label=r"$\theta_{0}$",
            linestyle=":",
        )

        draw_heading_arrow(
            ax=ax,
            angle=result[
                "segment_reference_error"
            ],
            length=0.38 * R,
            label=r"$\theta_{S}$",
            linestyle="--",
        )

        ax.axhline(
            0.0,
            linestyle=":",
            linewidth=0.8,
            alpha=0.65,
        )

        ax.set_title(
            rf"target $\delta_{{\mathrm{{ref}}}}="
            rf"{target_mismatch:.0f}^\circ$"
            "\n"
            rf"actual: "
            rf"${result['delta_reference_degrees']:.1f}^\circ$, "
            rf"{result['family_latex']}, "
            rf"$\tau_{{0}}={result['tau0']:+d}$"
        )

        x_margin = (
            footprint_radius
            + 0.25
            * R
        )

        y_margin = (
            footprint_radius
            + 0.25
            * R
        )

        ax.set_xlim(
            np.min(
                coordinates[:, 0]
            )
            - x_margin,
            np.max(
                coordinates[:, 0]
            )
            + x_margin,
        )

        ax.set_ylim(
            np.min(
                coordinates[:, 1]
            )
            - y_margin,
            np.max(
                coordinates[:, 1]
            )
            + y_margin,
        )

        ax.set_aspect(
            "equal",
            adjustable="box",
        )

        ax.grid(
            True,
            linestyle=":",
            linewidth=0.45,
            alpha=0.30,
        )

        ax.set_xlabel(
            r"$s_{\mathrm{ref}}/R$"
        )

        ax.set_ylabel(
            r"$q_{\mathrm{ref}}/R$"
        )

        x_ticks = ax.get_xticks()
        y_ticks = ax.get_yticks()

        ax.set_xticks(
            x_ticks
        )

        ax.set_yticks(
            y_ticks
        )

        ax.set_xticklabels(
            [
                f"{tick / R:.1f}"
                for tick in x_ticks
            ]
        )

        ax.set_yticklabels(
            [
                f"{tick / R:.1f}"
                for tick in y_ticks
            ]
        )

    for unused_index in range(
        number_of_panels,
        len(
            axes_flat
        ),
    ):
        axes_flat[
            unused_index
        ].axis(
            "off"
        )

    figure.suptitle(
        "Initial maneuver versus signed reference-tangent mismatch",
        y=0.995,
    )

    figure.tight_layout(
        rect=(
            0.0,
            0.0,
            1.0,
            0.97,
        )
    )

    if output_path is not None:
        output_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        figure.savefig(
            output_path,
            bbox_inches="tight",
        )

    return (
        figure,
        axes,
        selected_results,
    )


