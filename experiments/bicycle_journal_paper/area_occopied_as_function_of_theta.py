# Sweep
# =====================================================================

def run_reference_tangent_sweep(
    *,
    bicycle: Bicycle,
    target_circle: IntermediateCircle,
    start_position: tuple[float, float],
    theta_step_degrees: float = 0.5,
    footprint_radius: float = 0.0,
) -> tuple[
    list[dict[str, Any]],
    list[dict[str, Any]],
    dict[str, Any],
]:
    """
    Sweep the initial orientation while keeping the reference tangent fixed.
    """
    if theta_step_degrees <= 0.0:
        raise ValueError(
            "theta_step_degrees must be positive."
        )

    start_position_array = np.asarray(
        start_position,
        dtype=float,
    )

    circle_center = np.array(
        [
            target_circle.center.x,
            target_circle.center.y,
        ],
        dtype=float,
    )

    circle_radius = float(
        target_circle.radius
    )

    tau1 = int(
        target_circle.turn_direction
    )

    reference_tangent = (
        compute_reference_tangent_from_turn_direction(
            start_position=start_position_array,
            circle_center=circle_center,
            circle_radius=circle_radius,
            tau1=tau1,
        )
    )

    theta_reference = float(
        reference_tangent[
            "heading"
        ]
    )

    theta0_values_degrees = np.arange(
        0.0,
        360.0,
        theta_step_degrees,
    )

    successful_results: list[
        dict[str, Any]
    ] = []

    failures: list[
        dict[str, Any]
    ] = []

    x0 = float(
        start_position_array[0]
    )

    y0 = float(
        start_position_array[1]
    )

    for theta0_degrees in theta0_values_degrees:
        theta0 = float(
            np.deg2rad(
                theta0_degrees
            )
        )

        start_pose = [
            x0,
            y0,
            theta0,
        ]

        try:
            trajectory = (
                compute_traj_to_circle_free_space_bicycle(
                    start_pose=start_pose,
                    bicycle=bicycle,
                    circ1=target_circle,
                )
            )

            extracted = (
                extract_initial_circular_maneuver(
                    trajectory
                )
            )

            world_coordinates = (
                concatenate_primitive_coordinates(
                    extracted[
                        "circular_primitives"
                    ]
                )
            )

            reference_coordinates = (
                transform_to_reference_frame(
                    world_coordinates=world_coordinates,
                    frame_origin=start_position_array,
                    theta_reference=theta_reference,
                )
            )

            theta_segment = float(
                extracted[
                    "tangent_segment"
                ].theta
            )

            delta_reference = (
                signed_angle_difference(
                    theta0,
                    theta_reference,
                )
            )

            delta_segment = (
                signed_angle_difference(
                    theta0,
                    theta_segment,
                )
            )

            segment_reference_error = (
                signed_angle_difference(
                    theta_segment,
                    theta_reference,
                )
            )

            decomposition_residual = float(
                wrap_to_pi(
                    delta_reference
                    - delta_segment
                    - segment_reference_error
                )
            )

            spatial_metrics = (
                compute_spatial_metrics(
                    reference_coordinates=reference_coordinates,
                    footprint_radius=footprint_radius,
                )
            )

            forward_arc = extracted[
                "forward_arc"
            ]

            backward_arc = extracted[
                "backward_arc"
            ]

            result = {
                "theta0": theta0,
                "theta0_degrees": float(
                    theta0_degrees
                ),
                "theta_reference": theta_reference,
                "theta_reference_degrees": float(
                    np.rad2deg(
                        theta_reference
                    )
                ),
                "theta_segment": theta_segment,
                "theta_segment_degrees": float(
                    np.rad2deg(
                        wrap_to_pi(
                            theta_segment
                        )
                    )
                ),
                "delta_reference": delta_reference,
                "delta_reference_degrees": float(
                    np.rad2deg(
                        delta_reference
                    )
                ),
                "delta_reference_abs_degrees": float(
                    abs(
                        np.rad2deg(
                            delta_reference
                        )
                    )
                ),
                "delta_segment": delta_segment,
                "delta_segment_degrees": float(
                    np.rad2deg(
                        delta_segment
                    )
                ),
                "delta_segment_abs_degrees": float(
                    abs(
                        np.rad2deg(
                            delta_segment
                        )
                    )
                ),
                "segment_reference_error": (
                    segment_reference_error
                ),
                "segment_reference_error_degrees": float(
                    np.rad2deg(
                        segment_reference_error
                    )
                ),
                "segment_reference_error_abs_degrees": float(
                    abs(
                        np.rad2deg(
                            segment_reference_error
                        )
                    )
                ),
                "angle_decomposition_residual": (
                    decomposition_residual
                ),
                "tau0": extracted[
                    "tau0"
                ],
                "tau1": tau1,
                "family_plain": extracted[
                    "family_plain"
                ],
                "family_latex": extracted[
                    "family_latex"
                ],
                "has_backward_arc": extracted[
                    "has_backward_arc"
                ],
                "forward_arc_iota_degrees": float(
                    np.rad2deg(
                        forward_arc.iota
                    )
                ),
                "backward_arc_iota_degrees": (
                    float(
                        np.rad2deg(
                            backward_arc.iota
                        )
                    )
                    if backward_arc is not None
                    else 0.0
                ),
                "world_coordinates": (
                    world_coordinates
                ),
                "reference_coordinates": (
                    reference_coordinates
                ),
                **spatial_metrics,
            }

            successful_results.append(
                result
            )

        except Exception as error:
            failures.append(
                {
                    "theta0_degrees": float(
                        theta0_degrees
                    ),
                    "error_type": type(
                        error
                    ).__name__,
                    "message": str(
                        error
                    ),
                }
            )

    return (
        successful_results,
        failures,
        reference_tangent,
    )


